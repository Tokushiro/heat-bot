import ExcelJS from 'exceljs';


type CellAddr = { r: number; c: number };

const COLS = 80; // Wide layout for complex grids
const FONT = 'Calibri';

// Helper to convert column number to letter (1 -> A, 2 -> B, etc.)
function col(n: number): string {
    let s = '';
    while (n > 0) {
        const m = (n - 1) % 26;
        s = String.fromCharCode(65 + m) + s;
        n = Math.floor((n - 1) / 26);
    }
    return s;
}

// Helper to create Excel range string
function range(a: CellAddr, b: CellAddr): string {
    return `${col(a.c)}${a.r}:${col(b.c)}${b.r}`;
}

// Set base worksheet properties
function setSheetBase(ws: ExcelJS.Worksheet) {
    ws.properties.defaultRowHeight = 15;
    ws.views = [{ state: 'normal' }];

    // Default column widths
    for (let i = 1; i <= COLS; i++) ws.getColumn(i).width = 2.5;

    // Print settings
    ws.pageSetup = {
        orientation: 'landscape',
        fitToPage: true,
        fitToWidth: 1,
        fitToHeight: 0,
        paperSize: 9, // A4
        horizontalCentered: true,
        margins: {
            left: 0.25,
            right: 0.25,
            top: 0.75,
            bottom: 0.75,
            header: 0.3,
            footer: 0.3
        }
    };
    ws.headerFooter.oddFooter = '&CGenerated by H.E.A.T. Bot System';
}

// Style a cell with common options
function styleCell(
    cell: ExcelJS.Cell,
    opts: Partial<ExcelJS.Style> & { value?: any } = {}
) {
    if ('value' in opts) cell.value = opts.value;

    cell.font = { name: FONT, size: 11, ...(opts.font || {}) };
    if (opts.alignment) cell.alignment = opts.alignment;
    if (opts.fill) cell.fill = opts.fill;
    if (opts.border) cell.border = opts.border;
    if (opts.numFmt) cell.numFmt = opts.numFmt;
}

// Add confidentiality banner
function addConfidentialBanner(ws: ExcelJS.Worksheet) {
    ws.mergeCells(range({ r: 2, c: 3 }, { r: 3, c: 12 }));
    const cell = ws.getCell('C2');
    styleCell(cell, {
        value: 'FOR INTERNAL USE ONLY\nDO NOT SHARE EXTERNALLY',
        font: { bold: true, size: 14, color: { argb: 'FFFF0000' } },
        alignment: { vertical: 'middle', horizontal: 'center', wrapText: true },
        fill: { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFFFFFFF' } },
        border: {
            top: { style: 'thin' },
            left: { style: 'thin' },
            bottom: { style: 'thin' },
            right: { style: 'thin' }
        }
    });
    ws.getRow(2).height = 30;
}

// Add big title
function addBigTitle(ws: ExcelJS.Worksheet, r: number, line1: string, line2: string) {
    ws.mergeCells(range({ r, c: 3 }, { r: r + 1, c: 12 }));
    const cell = ws.getCell(r, 3);
    styleCell(cell, {
        value: `${line1}\n${line2}`,
        font: { bold: true, size: 16 },
        alignment: { vertical: 'middle', horizontal: 'center', wrapText: true }
    });
    ws.getRow(r).height = 40;
}

// Add standard reference row
function addStandardRow(ws: ExcelJS.Worksheet, r: number, standard: string = 'IEC 63180 Ed. 1') {
    styleCell(ws.getCell(r, 3), { value: 'Standard', font: { bold: true } });
    ws.mergeCells(range({ r, c: 4 }, { r, c: 7 }));
    styleCell(ws.getCell(r, 4), { value: standard });
}

// Add metadata block
function addMetaBlock(
    ws: ExcelJS.Worksheet,
    startRow: number,
    entries: Array<{ label: string; value?: string }>
) {
    entries.forEach((e, idx) => {
        const r = startRow + idx;
        styleCell(ws.getCell(r, 3), { value: e.label, font: { bold: true } });
        ws.mergeCells(range({ r, c: 4 }, { r, c: 10 }));
        styleCell(ws.getCell(r, 4), {
            value: e.value ?? '',
            alignment: { vertical: 'middle', horizontal: 'left' }
        });
    });
}

// Convert polar coordinates to cartesian for grid positioning
function polarToCartesian(angle: number, distance: number): { x: number; y: number } {
    const radians = (angle * Math.PI) / 180;
    return {
        x: distance * Math.cos(radians),
        y: distance * Math.sin(radians)
    };
}

