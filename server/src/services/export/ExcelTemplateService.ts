    /**
     * Cell Count Tab - Detailed statistics per radius
     */
    private static buildCellCount(
        wb: ExcelJS.Workbook,
        tangentialData: TangentialMeasurement[]
    ) {
        const ws = wb.addWorksheet('Cell count - Tangential grid');
        setSheetBase(ws);

        for (let i = 3; i <= 10; i++) ws.getColumn(i).width = 12;

        addConfidentialBanner(ws);
        addBigTitle(ws, 5, 'CELL COUNT', 'TANGENTIAL GRID VALIDATION (15% RULE)');

        // Group by distance
        const distanceMap = new Map<number, TangentialMeasurement[]>();
        tangentialData.forEach(t => {
            const dist = Math.round(t.distance);
            if (!distanceMap.has(dist)) distanceMap.set(dist, []);
            distanceMap.get(dist)!.push(t);
        });

        const distances = Array.from(distanceMap.keys()).sort((a, b) => a - b);

        // Explanation
        ws.mergeCells(range({ r: 8, c: 3 }, { r: 8, c: 10 }));
        styleCell(ws.getCell(8, 3), {
            value: 'IEC 63180 requires 85% detection rate within coverage area (15% tolerance)',
            font: { italic: true, size: 10 }
        });

        // Table
        const tableStart = 11;
        const headers = ['Radius (m)', '# cells', '# cells OK', 'Detection Rate', 'Allowed NOK (15%)', 'Status'];

        headers.forEach((header, i) => {
            styleCell(ws.getCell(tableStart, 3 + i), {
                value: header,
                font: { bold: true },
                alignment: { horizontal: 'center', vertical: 'middle' },
                fill: { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFD9E1F2' } }
            });
        });

        distances.forEach((dist, i) => {
            const r = tableStart + 1 + i;
            const measurements = distanceMap.get(dist)!;
            const total = measurements.length;
            const detected = measurements.filter(m => m.detected).length;
            const rate = (detected / total) * 100;
            const allowedFail = Math.ceil(total * 0.15);
            const passes = rate >= 85;

            styleCell(ws.getCell(r, 3), { value: dist });
            styleCell(ws.getCell(r, 4), { value: total });
            styleCell(ws.getCell(r, 5), { value: detected });
            styleCell(ws.getCell(r, 6), { value: rate, numFmt: '0.0"%"' });
            styleCell(ws.getCell(r, 7), { value: allowedFail });
            styleCell(ws.getCell(r, 8), {
                value: passes ? 'PASS' : 'FAIL',
                font: { bold: true },
                fill: {
                    type: 'pattern',
                    pattern: 'solid',
                    fgColor: { argb: passes ? 'FF92D050' : 'FFFFC7CE' }
                },
                alignment: { horizontal: 'center' }
            });

            for (let col = 3; col <= 8; col++) {
                ws.getCell(r, col).border = {
                    top: { style: 'thin' },
                    left: { style: 'thin' },
                    bottom: { style: 'thin' },
                    right: { style: 'thin' }
                };
            }
        });
    }
